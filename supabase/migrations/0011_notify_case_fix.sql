-- Падежи в текстах уведомлений.
--
-- «Не хватает 341 очка» — родительный. «Отстаёт на 341 очко» — винительный.
-- Один набор форм на оба оборота давал «отстаёт на 341 очка»: формально
-- почти незаметно, но именно из таких мелочей складывается ощущение, что
-- текст писал не человек.
--
-- Полный текст функции notification_batch — в миграции 0010, здесь меняется
-- только оборот для первого места.

create or replace function app.score_words_acc(n bigint) returns text
language sql immutable set search_path = ''
as $$
  select app.fmt_score(n) || ' ' || app.plural(n, 'очко', 'очка', 'очков')
$$;

